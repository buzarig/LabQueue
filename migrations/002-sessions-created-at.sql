-- Час створення заняття (spec лаби 4, критерій 8): лише розширення схеми,
-- сумісне зі старою версією. Код колонку не читає й не пише: стара й нова
-- версії вставляють заняття з явним переліком колонок, значення ставить БД.
-- На PostgreSQL 17 ADD COLUMN зі стабільним типовим значенням не переписує
-- таблицю: наявні рядки отримують момент міграції.
alter table sessions.sessions
  add column created_at timestamptz not null default now();
